  <div class="section-head">
    <p class="eyebrow">How to</p>
    <h2 id="how-heading">How to remove content credentials from an image</h2>
    <p>
      Three steps, no account and no upload. The whole process runs on your own
      device, so the image never reaches a server.
    </p>
  </div>

  <ol class="howto">
    <li>
      <h3>Add the image</h3>
      <p>
        Drop a JPEG, PNG, TIFF, HEIC or AVIF file onto the tool, choose one from
        your device, or paste from the clipboard.
      </p>
    </li>
    <li>
      <h3>Review what is hidden</h3>
      <p>
        Untrace lists every metadata block it finds — C2PA content credentials,
        AI generation tags, GPS coordinates, camera details and timestamps.
      </p>
    </li>
    <li>
      <h3>Clean and download</h3>
      <p>
        The image is decoded to pixels and written back out, which leaves every
        metadata container behind. Download the clean copy.
      </p>
    </li>
  </ol>
